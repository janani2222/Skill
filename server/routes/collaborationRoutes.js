const express = require('express');
const { protect } = require('../middleware/authMiddleware');
const controller = require('../controllers/collaborationController');
const upload = require('../middleware/uploadMiddleware');
const router = express.Router();
router.use(protect);
router.get('/explore', controller.explore);
router.get('/current-projects', controller.listCurrentProjects);
router.get('/requests', controller.listRequests);
router.post('/projects/:id/requests', controller.createRequest);
router.patch('/requests/:requestId', controller.updateRequest);
router.get('/notifications', controller.listNotifications);
router.patch('/notifications/read-all', controller.markNotificationsRead);
router.patch('/notifications/:notificationId/read', controller.markNotificationRead);
router.get('/conversations', controller.listConversations);
router.post('/direct/:studentId', controller.startDirectConversation);
router.get('/conversations/:conversationId', controller.getConversation);
router.post('/conversations/:conversationId/messages', upload.uploadChatAttachment.single('file'), controller.sendConversationMessage);
router.get('/projects/:id/access', controller.getProjectAccess);
router.get('/chat/:projectId', controller.getChat);
router.post('/chat/:projectId/messages', upload.uploadChatAttachment.single('file'), controller.sendChatMessage);
module.exports = router;
